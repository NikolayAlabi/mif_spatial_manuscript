def norm_str(x) -> str:
    if pd.isna(x):
        return ""
    return re.sub(r"\s+", " ", str(x)).strip()


def normalize_panel(x) -> str:
    s = norm_str(x).upper()
    if s in {"AR", "ARP"}:
        return "AR"
    if s in {"BT", "B&T", "B+T", "B_T", "B T"}:
        return "BT"
    if s in {"MY", "M", "MYELOID"}:
        return "MY"
    return norm_str(x)


def normalize_cohort(x) -> str:
    s = norm_str(x)
    su = s.upper().replace("_", " ").replace("-", "")
    if su in {"BCA2020", "BCA 2020", "NAC2020"}:
        return "NAC2020"
    if su in {"NONAC", "NO NAC"}:
        return "No-NAC"
    if su == "PURE01":
        return "PURE01"
    if su == "BLASST":
        return "BLASST"
    if su == "NAC2015" or su.startswith("BLADDER"):
        return "NAC2015"
    if su in {"KOLL", "FLORESTAN"}:
        return "KOLL"
    return s


def normalize_sample_type(x) -> str:
    s = norm_str(x).upper()
    if "TURBT" in s:
        return "TURBT"
    if s == "RC" or "CYSTECTOMY" in s:
        return "RC"
    return norm_str(x) if norm_str(x) else "Unknown"


def normalize_qc(x) -> str:
    s = norm_str(x)
    if s == "" or s.lower() in {"nan", "none", "na", "<na>", "unknown"}:
        return "Missing QC"
    sl = s.lower()
    if sl in {"acceptable", "accepted", "accept", "good", "pass", "usable"}:
        return "Acceptable"
    if sl in {"borderline", "borderline usable", "borderline/usable"}:
        return "Borderline"
    if sl in {"unusable", "fail", "failed", "bad", "reject", "rejected"}:
        return "Unusable"
    return s


def normalize_region_from_prep(assigned_loc, tumor_stroma=None) -> str:
    """Convert prep region labels to Epi/Stroma/Other."""
    s = norm_str(assigned_loc).lower()
    t = norm_str(tumor_stroma).lower()
    if s in {"epithelial", "epi", "tumor", "tumour"} or t in {"tumor", "tumour", "epi", "epithelial"}:
        return "Epi"
    if s in {"stroma", "str"} or t in {"stroma", "str"}:
        return "Stroma"
    return "Other"


def base_label(label: str) -> str:
    """Return base label before checkpoint-state suffix."""
    s = norm_str(label)
    if "__" in s:
        return s.split("__", 1)[0]
    return s


def is_excluded_label(label: str) -> bool:
    """Heuristic flag for labels excluded from primary analysis."""
    s = norm_str(label).lower()
    b = base_label(s).lower()
    if b in EXCLUDED_BASE_LABELS or s in EXCLUDED_BASE_LABELS:
        return True
    if any(tok in s for tok in ["artifact", "unresolved", "mixed_lineage", "mixed-lineage", "mixed lineage"]):
        return True
    return False


def safe_filename(x: str) -> str:
    x = norm_str(x)
    x = re.sub(r"[^A-Za-z0-9._-]+", "_", x)
    x = re.sub(r"_+", "_", x).strip("_")
    return x or "NA"


