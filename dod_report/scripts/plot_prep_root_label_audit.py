def label_color_map(labels: Iterable[str], excluded_flags: Optional[dict[str, bool]] = None) -> dict[str, str]:
    labels = list(labels)
    cmap = plt.get_cmap("tab20")
    out = {}
    i = 0
    for lab in labels:
        if excluded_flags and excluded_flags.get(lab, False):
            out[lab] = "#d62728"
        else:
            b = base_label(lab)
            out[lab] = BASE_LABEL_COLORS.get(lab, BASE_LABEL_COLORS.get(b, cmap(i % 20)))
            i += 1
    return out


def maybe_group_minor_labels(df: pd.DataFrame, value_col: str, label_col: str = "label", max_labels: int = 25) -> pd.DataFrame:
    """Group small labels into 'Other labels' for stacked bar readability."""
    totals = df.groupby(label_col, dropna=False)[value_col].sum().sort_values(ascending=False)
    keep = set(totals.head(max_labels).index.astype(str))
    out = df.copy()
    out[label_col] = out[label_col].astype(str)
    out.loc[~out[label_col].isin(keep), label_col] = "Other labels"
    return out


def plot_mean_cell_count_composition(
    comp: pd.DataFrame,
    prep_root: str,
    panel: str,
    out_dir: Path,
    cohorts: list[str],
    prefix: str,
    max_stacked_labels: int = 25,
):
    sub = comp[(comp["prep_root"].eq(prep_root)) & (comp["panel"].eq(panel)) & (comp["cohort"].isin(cohorts))].copy()
    if sub.empty:
        return None

    sub = sub[sub["region_class"].isin(REGION_ORDER)].copy()
    sub["cohort"] = pd.Categorical(sub["cohort"], categories=cohorts, ordered=True)
    sub["sample_type"] = pd.Categorical(sub["sample_type"], categories=SAMPLE_TYPE_ORDER, ordered=True)
    sub["region_class"] = pd.Categorical(sub["region_class"], categories=REGION_ORDER, ordered=True)

    plot_df = maybe_group_minor_labels(sub, "mean_cells_per_unit", max_labels=max_stacked_labels)
    plot_df = (
        plot_df.groupby(["cohort", "sample_type", "region_class", "label"], observed=False, dropna=False)["mean_cells_per_unit"]
        .sum()
        .reset_index()
    )

    x_df = plot_df[["cohort", "sample_type", "region_class"]].drop_duplicates().sort_values(["cohort", "sample_type", "region_class"])
    x_df = x_df[(x_df["cohort"].isin(cohorts)) & (x_df["sample_type"].isin(SAMPLE_TYPE_ORDER)) & (x_df["region_class"].isin(REGION_ORDER))]
    x_df = x_df.reset_index(drop=True)
    x_df["x"] = np.arange(len(x_df))
    plot_df = plot_df.merge(x_df, on=["cohort", "sample_type", "region_class"], how="inner")

    labels = plot_df.groupby("label")["mean_cells_per_unit"].sum().sort_values(ascending=False).index.tolist()
    excl = {lab: is_excluded_label(lab) for lab in labels}
    colors = label_color_map(labels, excl)

    fig_w = max(12, 0.42 * len(x_df) + 4)
    fig, ax = plt.subplots(figsize=(fig_w, 5.2))
    bottom = np.zeros(len(x_df))

    for lab in labels:
        vals = (
            plot_df[plot_df["label"].eq(lab)]
            .set_index("x")["mean_cells_per_unit"]
            .reindex(x_df["x"].values)
            .fillna(0)
            .to_numpy()
        )
        ax.bar(x_df["x"], vals, bottom=bottom, label=lab, color=colors[lab], edgecolor="black", linewidth=0.2)
        bottom += vals

    tick_labels = [f"{r.cohort}\n{r.sample_type}\n{r.region_class}" for r in x_df.itertuples(index=False)]
    ax.set_xticks(x_df["x"])
    ax.set_xticklabels(tick_labels, rotation=55, ha="right", fontsize=8)
    ax.set_ylabel("Mean cells per core/image/region")
    ax.set_title(f"{prep_root} — {panel}: mean cell-count composition in Epi vs Stroma")
    ax.grid(axis="y", alpha=0.25)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)

    # Vertical separators between cohorts.
    for cohort in cohorts[:-1]:
        idx = x_df.index[x_df["cohort"].astype(str).eq(cohort)]
        if len(idx):
            ax.axvline(idx.max() + 0.5, color="black", linewidth=0.6, alpha=0.35)

    ax.legend(title="Final label", bbox_to_anchor=(1.02, 1), loc="upper left", fontsize=7, frameon=True)
    fig.tight_layout()

    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{prefix}_{safe_filename(prep_root)}_{panel}_mean_cell_count_composition"
    fig.savefig(out_dir / f"{stem}.pdf", bbox_inches="tight")
    fig.savefig(out_dir / f"{stem}.png", dpi=300, bbox_inches="tight")
    plt.close(fig)
    return out_dir / f"{stem}.png"


def plot_abundance_consistency(
    label_summary: pd.DataFrame,
    prep_root: str,
    panel: str,
    out_dir: Path,
    include_blasst: bool,
    counts: pd.DataFrame,
    prefix: str,
    annotate_top_n: int = 30,
):
    cohorts = REPORT_COHORTS if include_blasst else REPORT_COHORTS_NO_BLASST
    sub_counts = counts[
        counts["prep_root"].eq(prep_root)
        & counts["panel"].eq(panel)
        & counts["cohort"].isin(cohorts)
    ].copy()
    if sub_counts.empty:
        return None

    sub_summary = make_label_summary(sub_counts)
    if sub_summary.empty:
        return None

    x = sub_summary["fraction_units_present"].clip(lower=1e-9)
    y = sub_summary["median_fraction_when_present"].clip(lower=1e-8)
    sizes = np.sqrt(sub_summary["n_cells"].astype(float))
    sizes = 30 + 2400 * (sizes / sizes.max())
    colors = np.where(sub_summary["excluded_from_primary"], "#d62728", "#1f77b4")

    fig, ax = plt.subplots(figsize=(9.5, 6.2))
    ax.scatter(x, y, s=sizes, c=colors, alpha=0.75, edgecolor="black", linewidth=0.5)
    ax.set_yscale("log")
    ax.set_xlim(-0.03, 1.03)
    ax.set_xlabel("Fraction of cores/regions where label appears")
    ax.set_ylabel("Median cell fraction within positive cores/regions")
    suffix = "with BLASST" if include_blasst else "without BLASST"
    ax.set_title(f"Abundance vs consistency — {prep_root}, panel={panel} ({suffix})")
    ax.grid(alpha=0.25)

    ann = sub_summary.sort_values("n_cells", ascending=False).head(annotate_top_n)
    for row in ann.itertuples(index=False):
        ax.text(row.fraction_units_present, max(row.median_fraction_when_present, 1e-8), str(row.label), fontsize=7)

    handles = [
        Patch(facecolor="#1f77b4", edgecolor="black", label="Primary/included label"),
        Patch(facecolor="#d62728", edgecolor="black", label="Excluded/non-primary label"),
    ]
    ax.legend(handles=handles, loc="lower right", frameon=True)
    fig.tight_layout()

    out_dir.mkdir(parents=True, exist_ok=True)
    stem = f"{prefix}_{safe_filename(prep_root)}_{panel}_abundance_consistency_{'withBLASST' if include_blasst else 'noBLASST'}"
    fig.savefig(out_dir / f"{stem}.pdf", bbox_inches="tight")
    fig.savefig(out_dir / f"{stem}.png", dpi=300, bbox_inches="tight")
    sub_summary.to_csv(out_dir / f"{stem}.source_data.csv", index=False)
    plt.close(fig)
    return out_dir / f"{stem}.png"


def plot_heatmap_matrix(
    mat: pd.DataFrame,
    title: str,
    out_prefix: Path,
    value_label: str = "Cell fraction",
    cmap: str = "viridis",
):
    if mat.empty:
        return None
    fig_h = max(4.5, 0.22 * mat.shape[0] + 1.5)
    fig_w = max(6.5, 1.1 * mat.shape[1] + 2.5)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    im = ax.imshow(mat.values, aspect="auto", interpolation="nearest", cmap=cmap)
    ax.set_xticks(np.arange(mat.shape[1]))
    ax.set_xticklabels(mat.columns, rotation=45, ha="right")
    ax.set_yticks(np.arange(mat.shape[0]))
    ax.set_yticklabels(mat.index, fontsize=7)
    ax.set_title(title)
    cb = fig.colorbar(im, ax=ax, fraction=0.035, pad=0.02)
    cb.set_label(value_label)
    fig.tight_layout()
    out_prefix.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(str(out_prefix) + ".pdf", bbox_inches="tight")
    fig.savefig(str(out_prefix) + ".png", dpi=300, bbox_inches="tight")
    mat.to_csv(str(out_prefix) + ".source_data.csv")
    plt.close(fig)
    return str(out_prefix) + ".png"


def plot_label_proportion_heatmaps(
    counts: pd.DataFrame,
    out_dir: Path,
    prefix: str,
    top_n: int = 40,
):
    outputs = []
    by_cohort = make_label_by_cohort_summary(counts)
    # Aggregate TURBT/RC together for the cohort-proportional heatmap, as requested.
    total_by_context = (
        by_cohort.groupby(["prep_root", "panel", "cohort", "label", "excluded_from_primary"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
    )
    totals = total_by_context.groupby(["prep_root", "panel", "cohort"], dropna=False)["n_cells"].sum().reset_index(name="total_cells")
    total_by_context = total_by_context.merge(totals, on=["prep_root", "panel", "cohort"], how="left")
    total_by_context["cell_fraction"] = total_by_context["n_cells"] / total_by_context["total_cells"].replace(0, np.nan)

    for include_blasst in [False, True]:
        cohorts = REPORT_COHORTS if include_blasst else REPORT_COHORTS_NO_BLASST
        for (prep_root, panel), sub in total_by_context.groupby(["prep_root", "panel"], dropna=False):
            sub = sub[sub["cohort"].isin(cohorts)].copy()
            if sub.empty:
                continue
            top = sub.groupby("label")["n_cells"].sum().sort_values(ascending=False).head(top_n).index
            sub = sub[sub["label"].isin(top)].copy()
            mat = sub.pivot_table(index="label", columns="cohort", values="cell_fraction", aggfunc="sum", fill_value=0)
            mat = mat.reindex(columns=cohorts).fillna(0)
            mat = mat.loc[mat.sum(axis=1).sort_values(ascending=False).index]
            suffix = "withBLASST" if include_blasst else "noBLASST"
            stem = out_dir / f"{prefix}_{safe_filename(prep_root)}_{panel}_label_proportion_heatmap_{suffix}"
            out = plot_heatmap_matrix(
                mat,
                title=f"{prep_root} — {panel}: final label proportions ({suffix})",
                out_prefix=stem,
                value_label="Fraction of cells within cohort/panel",
                cmap="viridis",
            )
            if out:
                outputs.append(out)
    return outputs


def plot_marker_combo_heatmaps(
    marker_summary: pd.DataFrame,
    out_dir: Path,
    prefix: str,
    top_n: int = 40,
):
    outputs = []
    if marker_summary.empty:
        return outputs

    marker_summary = marker_summary.copy()
    marker_summary["row_label"] = marker_summary["marker_combo"].astype(str) + " → " + marker_summary["collapse_label"].astype(str)
    agg = (
        marker_summary.groupby(["panel", "cohort", "row_label", "excluded_from_primary"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
    )
    totals = agg.groupby(["panel", "cohort"], dropna=False)["n_cells"].sum().reset_index(name="total_cells")
    agg = agg.merge(totals, on=["panel", "cohort"], how="left")
    agg["cell_fraction"] = agg["n_cells"] / agg["total_cells"].replace(0, np.nan)

    for include_blasst in [False, True]:
        cohorts = REPORT_COHORTS if include_blasst else REPORT_COHORTS_NO_BLASST
        for panel, sub in agg.groupby("panel", dropna=False):
            if panel not in PANEL_ORDER:
                continue
            sub = sub[sub["cohort"].isin(cohorts)].copy()
            if sub.empty:
                continue
            top = sub.groupby("row_label")["n_cells"].sum().sort_values(ascending=False).head(top_n).index
            sub = sub[sub["row_label"].isin(top)].copy()
            mat = sub.pivot_table(index="row_label", columns="cohort", values="cell_fraction", aggfunc="sum", fill_value=0)
            mat = mat.reindex(columns=cohorts).fillna(0)
            mat = mat.loc[mat.sum(axis=1).sort_values(ascending=False).index]
            suffix = "withBLASST" if include_blasst else "noBLASST"
            stem = out_dir / f"{prefix}_{panel}_marker_combo_proportion_heatmap_{suffix}"
            out = plot_heatmap_matrix(
                mat,
                title=f"{panel}: marker-combination proportions ({suffix})",
                out_prefix=stem,
                value_label="Fraction of cells within cohort/panel",
                cmap="magma",
            )
            if out:
                outputs.append(out)
    return outputs


