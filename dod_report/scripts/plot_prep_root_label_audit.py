def prep_root_paths(weibull_root: Path = DEFAULT_WEIBULL_ROOT, prep_roots: Optional[dict[str, str]] = None) -> dict[str, Path]:
    prep_roots = prep_roots or DEFAULT_PREP_ROOTS
    return {name: (weibull_root / subdir) for name, subdir in prep_roots.items()}


def iter_1nn_files(root: Path):
    yield from sorted(root.rglob("1NN_prep.tsv"))


def read_1nn_counts_for_root(root_name: str, root: Path) -> pd.DataFrame:
    """Aggregate all 1NN_prep.tsv chunks to unit/region/label counts."""
    files = list(iter_1nn_files(root))
    if not files:
        print(f"[WARN] No 1NN_prep.tsv files found under {root}")
        return pd.DataFrame()

    usecols = ["sample_id", "coord", "Panel", "cohort", "phenotype", "assigned_loc", "tumor_stroma"]
    parts = []

    for i, fp in enumerate(files, 1):
        try:
            chunk = pd.read_csv(fp, sep="\t", usecols=lambda c: c in usecols, low_memory=False)
        except Exception as e:
            print(f"[WARN] Failed reading {fp}: {e}")
            continue

        required = ["sample_id", "coord", "Panel", "cohort", "phenotype"]
        missing = [c for c in required if c not in chunk.columns]
        if missing:
            print(f"[WARN] Skipping {fp}; missing columns: {missing}")
            continue

        if "assigned_loc" not in chunk.columns:
            chunk["assigned_loc"] = pd.NA
        if "tumor_stroma" not in chunk.columns:
            chunk["tumor_stroma"] = pd.NA

        chunk["prep_root"] = root_name
        chunk["panel"] = chunk["Panel"].map(normalize_panel)
        chunk["cohort"] = chunk["cohort"].map(normalize_cohort)
        chunk["label"] = chunk["phenotype"].astype(str).str.strip()
        chunk["region_class"] = [
            normalize_region_from_prep(a, t)
            for a, t in zip(chunk["assigned_loc"], chunk["tumor_stroma"])
        ]
        chunk["coord"] = chunk["coord"].astype(str).str.strip()
        chunk["sample_id"] = chunk["sample_id"].astype(str).str.strip()
        chunk["unit_key"] = chunk["panel"].astype(str) + "|" + chunk["cohort"].astype(str) + "|" + chunk["coord"].astype(str)

        g = (
            chunk.groupby(["prep_root", "panel", "cohort", "coord", "unit_key", "sample_id", "region_class", "label"], dropna=False)
            .size()
            .reset_index(name="n_cells")
        )
        parts.append(g)

        if i % 25 == 0:
            print(f"[INFO] {root_name}: processed {i}/{len(files)} chunks")

    if not parts:
        return pd.DataFrame()

    out = pd.concat(parts, ignore_index=True)
    out = (
        out.groupby(["prep_root", "panel", "cohort", "coord", "unit_key", "sample_id", "region_class", "label"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
    )
    out["label_base"] = out["label"].map(base_label)
    out["excluded_from_primary"] = out["label"].map(is_excluded_label)
    return out


def load_all_prep_counts(
    weibull_root: Path = DEFAULT_WEIBULL_ROOT,
    prep_roots: Optional[dict[str, str]] = None,
    valid_units: Optional[pd.DataFrame] = None,
) -> pd.DataFrame:
    """Load/aggregate all configured prep roots and apply valid-unit filter."""
    paths = prep_root_paths(weibull_root, prep_roots)
    parts = []
    for root_name, root in paths.items():
        print(f"\n[LOAD] {root_name}: {root}")
        df = read_1nn_counts_for_root(root_name, root)
        if df.empty:
            continue
        parts.append(df)

    if not parts:
        raise ValueError("No prep-root counts could be loaded.")

    counts = pd.concat(parts, ignore_index=True)

    if valid_units is not None and not valid_units.empty:
        meta = valid_units[["unit_key", "sample_type", "branch", "qc_status"]].drop_duplicates("unit_key")
        counts = counts.merge(meta, on="unit_key", how="inner")
    else:
        counts["sample_type"] = "Unknown"
        counts["branch"] = pd.NA
        counts["qc_status"] = pd.NA

    counts = counts[counts["cohort"].isin(REPORT_COHORTS)].copy()
    counts = counts[counts["panel"].isin(PANEL_ORDER)].copy()
    counts = counts[counts["region_class"].isin(REGION_ORDER)].copy()

    return counts.reset_index(drop=True)


