def load_valid_units(
    qc_dir: Path = DEFAULT_QC_DIR,
    cohorts: list[str] | None = None,
    panels: list[str] | None = None,
    keep_qc_statuses: list[str] | None = None,
    require_all_primary_inputs: bool = True,
) -> pd.DataFrame:
    """Load source_presence_all.csv and return valid coord/panel/cohort units."""
    cohorts = cohorts or REPORT_COHORTS
    panels = panels or PANEL_ORDER
    keep_qc_statuses = keep_qc_statuses or ["Acceptable", "Borderline"]

    fp = qc_dir / "source_presence_all.csv"
    if not fp.exists():
        raise FileNotFoundError(f"Missing QC source-presence file: {fp}")

    d = pd.read_csv(fp, low_memory=False)
    for c in ["branch", "panel", "cohort_label", "sample_type", "coord"]:
        if c not in d.columns:
            d[c] = pd.NA

    d["panel"] = d["panel"].map(normalize_panel)
    d["cohort"] = d["cohort_label"].map(normalize_cohort)
    d["sample_type"] = d["sample_type"].map(normalize_sample_type)
    d["qc_status"] = d.get("structural_acceptability", pd.Series(pd.NA, index=d.index)).map(normalize_qc)

    d = d[d["cohort"].isin(cohorts)].copy()
    d = d[d["panel"].isin(panels)].copy()
    d = d[d["coord"].notna()].copy()

    if require_all_primary_inputs and "has_all_primary_inputs" in d.columns:
        d["has_all_primary_inputs"] = d["has_all_primary_inputs"].fillna(False).astype(bool)
        d = d[d["has_all_primary_inputs"]].copy()

    is_tma = d["branch"].astype(str).eq("TMA")
    d = d[(~is_tma) | (is_tma & d["qc_status"].isin(keep_qc_statuses))].copy()

    keep = [
        "branch", "panel", "cohort", "sample_type", "coord", "qc_status",
        "has_all_primary_inputs", "n_parquet_cells", "entity_id",
    ]
    keep = [c for c in keep if c in d.columns]
    out = d[keep].drop_duplicates(["panel", "cohort", "coord"]).copy()
    out["unit_key"] = out["panel"].astype(str) + "|" + out["cohort"].astype(str) + "|" + out["coord"].astype(str)
    return out.reset_index(drop=True)


