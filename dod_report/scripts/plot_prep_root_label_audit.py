def load_cell_df_counts(
    cell_dir: Path = DEFAULT_CELL_DIR,
    valid_units: Optional[pd.DataFrame] = None,
    include_whole: bool = True,
) -> pd.DataFrame:
    files = [cell_dir / "tma_cell_df.parquet"]
    if include_whole:
        files.append(cell_dir / "wholesection_cell_df.parquet")

    parts = []
    cols_wanted = [
        "sample_name", "coord", "Panel", "cohort", "marker_combination",
        "phenotype", "phenotype_canonical", "collapse_label", "state", "tissue_region",
    ]

    for fp in files:
        if not fp.exists():
            print(f"[WARN] Missing cell_df parquet: {fp}")
            continue
        try:
            import pyarrow.parquet as pq
            available_cols = set(pq.read_schema(fp).names)
            keep = [c for c in cols_wanted if c in available_cols]
            df = pd.read_parquet(fp, columns=keep)
        except Exception:
            # Fall back to reading the full parquet if schema inspection fails.
            df0 = pd.read_parquet(fp)
            keep = [c for c in cols_wanted if c in df0.columns]
            df = df0[keep].copy()
            del df0

        for c in ["coord", "Panel", "cohort"]:
            if c not in df.columns:
                raise ValueError(f"{fp} missing required column: {c}")
        df["panel"] = df["Panel"].map(normalize_panel)
        df["cohort"] = df["cohort"].map(normalize_cohort)
        df["coord"] = df["coord"].astype(str).str.strip()
        df["unit_key"] = df["panel"].astype(str) + "|" + df["cohort"].astype(str) + "|" + df["coord"].astype(str)

        if "marker_combination" in df.columns:
            df["marker_combo"] = df["marker_combination"].fillna("ALL_NEG").astype(str).str.strip()
        elif "phenotype_canonical" in df.columns:
            df["marker_combo"] = df["phenotype_canonical"].fillna("ALL_NEG").astype(str).str.strip()
        elif "phenotype" in df.columns:
            df["marker_combo"] = df["phenotype"].fillna("ALL_NEG").astype(str).str.strip()
        else:
            df["marker_combo"] = "Unknown"

        if "collapse_label" not in df.columns:
            df["collapse_label"] = "Unknown"
        if "state" not in df.columns:
            df["state"] = pd.NA

        df["collapse_label"] = df["collapse_label"].astype(str).str.strip()
        df["excluded_from_primary"] = df["collapse_label"].map(is_excluded_label)
        parts.append(df[["unit_key", "panel", "cohort", "coord", "marker_combo", "collapse_label", "state", "excluded_from_primary"]].copy())

    if not parts:
        return pd.DataFrame()

    out = pd.concat(parts, ignore_index=True)
    out = out[out["cohort"].isin(REPORT_COHORTS)].copy()
    out = out[out["panel"].isin(PANEL_ORDER)].copy()

    if valid_units is not None and not valid_units.empty:
        meta = valid_units[["unit_key", "sample_type", "branch", "qc_status"]].drop_duplicates("unit_key")
        out = out.merge(meta, on="unit_key", how="inner")
    else:
        out["sample_type"] = "Unknown"
        out["branch"] = pd.NA
        out["qc_status"] = pd.NA

    g = (
        out.groupby(["panel", "cohort", "sample_type", "marker_combo", "collapse_label", "state", "excluded_from_primary"], dropna=False)
        .size()
        .reset_index(name="n_cells")
    )
    totals = g.groupby(["panel", "cohort"], dropna=False)["n_cells"].sum().reset_index(name="total_cells_panel_cohort")
    g = g.merge(totals, on=["panel", "cohort"], how="left")
    g["cell_fraction_within_panel_cohort"] = g["n_cells"] / g["total_cells_panel_cohort"].replace(0, np.nan)
    return g.sort_values(["panel", "cohort", "n_cells"], ascending=[True, True, False]).reset_index(drop=True)


