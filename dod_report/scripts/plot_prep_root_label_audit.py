def build_all_outputs(
    weibull_root: Path = DEFAULT_WEIBULL_ROOT,
    qc_dir: Path = DEFAULT_QC_DIR,
    cell_dir: Path = DEFAULT_CELL_DIR,
    out_dir: Path = DEFAULT_OUT_DIR,
    cohorts: list[str] | None = None,
    keep_qc_statuses: list[str] | None = None,
    require_all_primary_inputs: bool = True,
    top_n_heatmap: int = 40,
    max_stacked_labels: int = 25,
) -> dict:
    cohorts = cohorts or REPORT_COHORTS
    out_dir = Path(out_dir)
    plot_dir = out_dir / "plots"
    table_dir = out_dir / "tables"
    plot_dir.mkdir(parents=True, exist_ok=True)
    table_dir.mkdir(parents=True, exist_ok=True)

    valid_units = load_valid_units(
        qc_dir=qc_dir,
        cohorts=cohorts,
        panels=PANEL_ORDER,
        keep_qc_statuses=keep_qc_statuses,
        require_all_primary_inputs=require_all_primary_inputs,
    )
    valid_summary = make_valid_unit_summary(valid_units)
    valid_summary.to_csv(table_dir / "supp_table_valid_units_used_for_prep_root_audit.csv", index=False)

    counts = load_all_prep_counts(weibull_root=weibull_root, valid_units=valid_units)
    counts.to_csv(table_dir / "source_data_prep_root_unit_region_label_counts.csv", index=False)

    label_summary = make_label_summary(counts)
    label_summary.to_csv(table_dir / "supp_table_prep_root_label_summary.csv", index=False)

    label_by_cohort = make_label_by_cohort_summary(counts)
    label_by_cohort.to_csv(table_dir / "supp_table_prep_root_label_by_cohort_sample_type.csv", index=False)

    comp_summary = make_mean_composition_summary(counts)
    comp_summary.to_csv(table_dir / "supp_table_mean_cell_count_composition_by_region.csv", index=False)

    marker_summary = load_cell_df_counts(cell_dir=cell_dir, valid_units=valid_units, include_whole=True)
    if not marker_summary.empty:
        marker_summary.to_csv(table_dir / "supp_table_marker_combination_by_cohort.csv", index=False)

    # Prep-root inventory table.
    inv = []
    for root_name, root in prep_root_paths(weibull_root).items():
        files = list(iter_1nn_files(root)) if root.exists() else []
        inv.append({
            "prep_root": root_name,
            "path": str(root),
            "exists": root.exists(),
            "n_1NN_prep_files": len(files),
            "chunk_summary_exists": (root / "chunk_summary.tsv").exists(),
        })
    pd.DataFrame(inv).to_csv(table_dir / "supp_table_prep_root_inventory.csv", index=False)

    outputs = {
        "valid_units": valid_summary,
        "counts": counts,
        "label_summary": label_summary,
        "label_by_cohort": label_by_cohort,
        "composition_summary": comp_summary,
        "marker_summary": marker_summary,
        "plot_paths": [],
        "table_dir": table_dir,
        "plot_dir": plot_dir,
    }

    # Mean cell-count composition stacked bars.
    for prep_root in sorted(comp_summary["prep_root"].dropna().unique()):
        for panel in PANEL_ORDER:
            p = plot_mean_cell_count_composition(
                comp_summary,
                prep_root=prep_root,
                panel=panel,
                out_dir=plot_dir,
                cohorts=cohorts,
                prefix="report",
                max_stacked_labels=max_stacked_labels,
            )
            if p:
                outputs["plot_paths"].append(str(p))

    # Abundance vs consistency bubble plots: every prep root/panel, with and without BLASST.
    for prep_root in sorted(counts["prep_root"].dropna().unique()):
        for panel in PANEL_ORDER:
            for include_blasst in [False, True]:
                p = plot_abundance_consistency(
                    label_summary=label_summary,
                    prep_root=prep_root,
                    panel=panel,
                    out_dir=plot_dir,
                    include_blasst=include_blasst,
                    counts=counts,
                    prefix="report",
                    annotate_top_n=30,
                )
                if p:
                    outputs["plot_paths"].append(str(p))

    # Heatmaps.
    outputs["plot_paths"].extend(plot_label_proportion_heatmaps(counts, plot_dir, prefix="report", top_n=top_n_heatmap))
    outputs["plot_paths"].extend(plot_marker_combo_heatmaps(marker_summary, plot_dir, prefix="report", top_n=top_n_heatmap))

    # Data dictionary.
    dictionary = pd.DataFrame([
        {"file": "supp_table_valid_units_used_for_prep_root_audit.csv", "description": "QC/source-complete TMA cores and BLASST whole-section regions retained for report prep-root audits."},
        {"file": "source_data_prep_root_unit_region_label_counts.csv", "description": "Aggregated source data from 1NN_prep.tsv: one row per prep root/panel/cohort/unit/region/final label."},
        {"file": "supp_table_prep_root_label_summary.csv", "description": "Across-cohort abundance and consistency for each final prep-root label."},
        {"file": "supp_table_prep_root_label_by_cohort_sample_type.csv", "description": "Cell-count and cell-fraction summaries for each final label by cohort and sample type."},
        {"file": "supp_table_mean_cell_count_composition_by_region.csv", "description": "Mean cells per unit for each prep-root label in epithelial/tumor and stroma regions."},
        {"file": "supp_table_marker_combination_by_cohort.csv", "description": "Raw marker-combination/collapse-label cell fractions by cohort, sample type, and panel."},
        {"file": "supp_table_prep_root_inventory.csv", "description": "Discovered prep roots and number of 1NN_prep.tsv chunks."},
    ])
    dictionary.to_csv(table_dir / "prep_root_audit_table_dictionary.csv", index=False)

    print("\n[DONE] Prep-root label audit outputs")
    print(f"  Tables: {table_dir}")
    print(f"  Plots:  {plot_dir}")
    print(f"  n plots: {len(outputs['plot_paths'])}")
    return outputs


