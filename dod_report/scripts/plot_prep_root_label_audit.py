def make_valid_unit_summary(valid_units: pd.DataFrame) -> pd.DataFrame:
    return (
        valid_units.groupby(["cohort", "sample_type", "panel", "branch", "qc_status"], dropna=False)
        .agg(n_units=("unit_key", "nunique"), n_cells_qc=("n_parquet_cells", "sum"))
        .reset_index()
        .sort_values(["cohort", "sample_type", "panel", "branch", "qc_status"])
    )


def make_label_summary(counts: pd.DataFrame) -> pd.DataFrame:
    """Across all included cohorts for each prep root/panel/label."""
    unit_totals = (
        counts.groupby(["prep_root", "panel", "unit_key"], dropna=False)["n_cells"]
        .sum()
        .reset_index(name="unit_total_cells")
    )
    label_unit = (
        counts.groupby(["prep_root", "panel", "label", "label_base", "excluded_from_primary", "unit_key"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
        .merge(unit_totals, on=["prep_root", "panel", "unit_key"], how="left")
    )
    label_unit["unit_fraction"] = label_unit["n_cells"] / label_unit["unit_total_cells"].replace(0, np.nan)

    total_units = unit_totals.groupby(["prep_root", "panel"], dropna=False)["unit_key"].nunique().reset_index(name="n_units_total")

    summary = (
        label_unit.groupby(["prep_root", "panel", "label", "label_base", "excluded_from_primary"], dropna=False)
        .agg(
            n_cells=("n_cells", "sum"),
            n_units_present=("unit_key", "nunique"),
            median_fraction_when_present=("unit_fraction", "median"),
            mean_fraction_when_present=("unit_fraction", "mean"),
            max_fraction_when_present=("unit_fraction", "max"),
        )
        .reset_index()
        .merge(total_units, on=["prep_root", "panel"], how="left")
    )
    summary["fraction_units_present"] = summary["n_units_present"] / summary["n_units_total"].replace(0, np.nan)
    return summary.sort_values(["prep_root", "panel", "n_cells"], ascending=[True, True, False]).reset_index(drop=True)


def make_label_by_cohort_summary(counts: pd.DataFrame) -> pd.DataFrame:
    total = (
        counts.groupby(["prep_root", "panel", "cohort", "sample_type"], dropna=False)["n_cells"]
        .sum()
        .reset_index(name="total_cells")
    )
    g = (
        counts.groupby(["prep_root", "panel", "cohort", "sample_type", "label", "label_base", "excluded_from_primary"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
        .merge(total, on=["prep_root", "panel", "cohort", "sample_type"], how="left")
    )
    g["cell_fraction"] = g["n_cells"] / g["total_cells"].replace(0, np.nan)
    return g.sort_values(["prep_root", "panel", "cohort", "sample_type", "n_cells"], ascending=[True, True, True, True, False]).reset_index(drop=True)


def make_mean_composition_summary(counts: pd.DataFrame) -> pd.DataFrame:
    """Mean cells per unit for each label within cohort/sample/region groups."""
    group_cols = ["prep_root", "panel", "cohort", "sample_type", "region_class"]
    units = (
        counts.groupby(group_cols + ["unit_key"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
        .groupby(group_cols, dropna=False)["unit_key"]
        .nunique()
        .reset_index(name="n_units")
    )
    totals = (
        counts.groupby(group_cols + ["label", "label_base", "excluded_from_primary"], dropna=False)["n_cells"]
        .sum()
        .reset_index()
        .merge(units, on=group_cols, how="left")
    )
    totals["mean_cells_per_unit"] = totals["n_cells"] / totals["n_units"].replace(0, np.nan)
    return totals.sort_values(group_cols + ["n_cells"], ascending=[True, True, True, True, True, False]).reset_index(drop=True)


